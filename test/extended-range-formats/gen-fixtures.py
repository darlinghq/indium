#!/usr/bin/env python3
# Generates fixtures.hpp and fill-values.glsl of the extended-range-formats test from what a Mac printed
# (macos-27.0.1-arm64.txt, the output of mac-probe.m on macOS 27.0.1, arm64, a real Metal device): the values a shader
# reads for each code, the codes stored for each rendered value, the clear and the blend.
# Usage: gen-fixtures.py [macos-27.0.1-arm64.txt]
import sys

path = sys.argv[1] if len(sys.argv) > 1 else 'macos-27.0.1-arm64.txt'
sample, render, clear, blend = {}, {}, {}, {}
order = []
for line in open(path):
    w = line.split()
    if not w:
        continue
    if w[0] == 'sample':
        sample[(w[1], int(w[2]))] = [int(x, 16) for x in w[3:7]]
        if w[1] == 'BGRA10_XR':
            order.append(int(w[2]))
    elif w[0] == 'render':
        render[(w[1], int(w[2], 16))] = [int(x) for x in w[3:7]]
    elif w[0] == 'clear':
        clear[w[1]] = [int(x) for x in w[-4:]]
    elif w[0] == 'blend':
        blend[w[1]] = [int(x) for x in w[2:6]]

values = sorted({k[1] for k in render if k[0] == 'BGRA10_XR'}, key=lambda v: [k[1] for k in render if k[0] == 'BGRA10_XR'].index(v))
# render lines print blue green red alpha; the three color channels are equal for a value
out = ['// Generated by gen-fixtures.py from macos-27.0.1-arm64.txt (observed on macOS 27.0.1, arm64). Do not edit.',
       '#pragma once', '#include <stdint.h>', '',
       'typedef struct { uint32_t code; uint32_t linearBits; uint32_t srgbBits; uint32_t alphaBits; } CodeFixture;',
       'static const CodeFixture codeFixtures[] = {']
for c in order:
    out.append('\t{ %d, 0x%08x, 0x%08x, 0x%08x },' % (c, sample[('BGRA10_XR', c)][0], sample[('BGRA10_XR_sRGB', c)][0], sample[('BGRA10_XR', c)][3]))
out += ['};', '',
        '// the values rendered, and the codes they are stored as in each format (color, alpha)',
        'typedef struct { uint32_t valueBits; uint16_t linearCode; uint16_t srgbCode; uint16_t alphaCode; } WriteFixture;',
        'static const WriteFixture writeFixtures[] = {']
for v in values:
    lin, srgb = render[('BGRA10_XR', v)], render[('BGRA10_XR_sRGB', v)]
    assert lin[0] == lin[1] == lin[2] and srgb[0] == srgb[1] == srgb[2]
    out.append('\t{ 0x%08x, %d, %d, %d },' % (v, lin[0], srgb[0], lin[3]))
out.append('};')
out.append('')
b, bs = blend['BGRA10_XR'], blend['BGRA10_XR_sRGB']
out.append('// blending the source (1, 0, 2, 0.6) over the cleared destination (0.25, 0.5, 0.75, 1) with SourceAlpha and OneMinusSourceAlpha:')
out.append('// red, green, blue and alpha codes (the source blue 2.0 is clamped to the range of the format before it is blended)')
out.append('static const uint16_t blendLinearCodes[4] = { %d, %d, %d, %d };' % (b[2], b[1], b[0], b[3]))
out.append('static const uint16_t blendSrgbCodes[4] = { %d, %d, %d, %d };' % (bs[2], bs[1], bs[0], bs[3]))
out.append('')
out.append('// clearing to (1.5, -1.0, 0.5, 2.0): red, green, blue and alpha codes')
c, cs = clear['BGRA10_XR'], clear['BGRA10_XR_sRGB']
out.append('static const uint16_t clearLinearCodes[4] = { %d, %d, %d, %d };' % (c[2], c[1], c[0], c[3]))
out.append('static const uint16_t clearSrgbCodes[4] = { %d, %d, %d, %d };' % (cs[2], cs[1], cs[0], cs[3]))
out.append('')
out.append('// linear filtering of two neighbouring texels sampled halfway: filtering happens on shader values (computed from the')
out.append('// observed values of the two codes)')
import struct
def f(bits): return struct.unpack('<f', struct.pack('<I', bits))[0]
def bits(x): return struct.unpack('<I', struct.pack('<f', x))[0]
a, bcode = 400, 1000
# the codes 400 and 1000 are not in the observed list for sRGB filtering; the linear ones are, 1000 only
out.append('static const uint32_t filterCodeA = 385, filterCodeB = 1000;')
out.append('static const uint32_t filterLinearBits = 0x%08x;' % bits((f(sample[('BGRA10_XR', 385)][0]) + f(sample[('BGRA10_XR', 1000)][0])) / 2))
out.append('static const uint32_t filterSrgbBits = 0x%08x;' % bits((f(sample[('BGRA10_XR_sRGB', 385)][0]) + f(sample[('BGRA10_XR_sRGB', 1000)][0])) / 2))
open('fixtures.hpp', 'w').write('\n'.join(out) + '\n')

g = ['// Generated by gen-fixtures.py. Do not edit.', 'const int valueCount = %d;' % len(values),
     'const float fillValues[%d] = float[%d](' % (len(values), len(values)),
     ',\n'.join('\tuintBitsToFloat(0x%08xu)' % v for v in values), ');']
open('fill-values.glsl', 'w').write('\n'.join(g) + '\n')
print(len(values), 'values', len(order), 'codes')
