#!/usr/bin/env python3
# Generates fixtures.hpp and fill-values.glsl of the extended-range-formats test.
#
# The numbers come from the documented encoding of the formats (the MTLPixelFormat reference pages of
# BGRA10_XR, BGRA10_XR_sRGB, BGR10_XR and BGR10_XR_sRGB): shader_float = (code - 384) / 510, the sRGB variants
# apply the sRGB transfer function on top, alpha is clamped to 0..1. They are written here independently of
# the implementation (plain arithmetic, no table taken from it). None was observed on a Mac: no Metal device
# was available. test/extended-range-formats/mac-probe.m prints the same tables on a Mac; replace this
# generator's output with its output once that has been run.
import math, struct

def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]

def bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]

def srgb_decode(e):
    a = abs(e)
    v = a / 12.92 if a <= 0.04045 else ((a + 0.055) / 1.055) ** 2.4
    return -v if e < 0 else v

def srgb_encode(l):
    a = abs(l)
    v = a * 12.92 if a <= 0.0031308 else 1.055 * a ** (1 / 2.4) - 0.055
    return -v if l < 0 else v

def decode(code, srgb):
    e = f32((code - 384) / 510.0)
    return f32(srgb_decode(e)) if srgb else e

def encode(v, srgb, hi=1022):
    if math.isnan(v):
        v = 0.0
    e = srgb_encode(v) if srgb else v
    c = round(e * 510.0 + 384.0)  # python rounds half to even
    return max(0, min(hi, c))

def encode_alpha(v):
    if math.isnan(v):
        v = 0.0
    return max(384, min(894, round(v * 510.0 + 384.0)))

codes = [0, 1, 2, 100, 255, 383, 384, 385, 510, 639, 893, 894, 895, 1000, 1021, 1022, 1023]
# values to write; none is within a thousandth of a rounding boundary of any format
values = [-100.0, -1.0, -0.752941, -0.6, -0.5271, -0.3, -0.04, -0.001, 0.0, 0.0015, 0.0031308 * 2, 0.04, 0.1, 0.2,
          0.3333, 0.5, 0.7, 1.0, 1.1, 1.25098, 1.5, 1.66894, 2.0, 7.0, 100.0, float('nan')]

out = []
out.append('// Generated by gen-fixtures.py: values of the documented encoding (see the comment there). Do not edit.')
out.append('#pragma once')
out.append('#include <stdint.h>')
out.append('')
out.append('typedef struct { uint32_t code; uint32_t linearBits; uint32_t srgbBits; uint32_t alphaBits; } CodeFixture;')
out.append('static const CodeFixture codeFixtures[] = {')
for c in codes:
    alpha = f32(max(0.0, min(1.0, (c - 384) / 510.0)))
    out.append('\t{ %d, 0x%08x, 0x%08x, 0x%08x },' % (c, bits(decode(c, False)), bits(decode(c, True)), bits(alpha)))
out.append('};')
out.append('')
out.append('// the values rendered, and the codes they are stored as in each format (color, alpha)')
out.append('typedef struct { uint32_t valueBits; uint16_t linearCode; uint16_t srgbCode; uint16_t alphaCode; } WriteFixture;')
out.append('static const WriteFixture writeFixtures[] = {')
for v in values:
    out.append('\t{ 0x%08x, %d, %d, %d },' % (bits(f32(v)) if not math.isnan(v) else 0x7fc00000, encode(f32(v), False), encode(f32(v), True), encode_alpha(f32(v))))
out.append('};')
out.append('')
# blending: destination cleared to (0.25, 0.5, 0.75, 1), source (1, 0, 2, 0.6), SrcAlpha / OneMinusSrcAlpha
dst = [0.25, 0.5, 0.75]
src = [1.0, 0.0, 2.0]
sa = f32(0.6)
res = [f32(f32(src[i] * sa) + f32(dst[i] * f32(1 - sa))) for i in range(3)]
out.append('// blending the source (1, 0, 2, 0.6) over the cleared destination (0.25, 0.5, 0.75, 1) with SourceAlpha and OneMinusSourceAlpha')
out.append('static const uint16_t blendLinearCodes[3] = { %s };' % ', '.join(str(encode(r, False)) for r in res))
out.append('static const uint16_t blendSrgbCodes[3] = { %s };' % ', '.join(str(encode(r, True)) for r in res))
out.append('static const uint16_t blendAlphaCode = %d;' % encode_alpha(f32(f32(sa * sa) + f32(1.0 * f32(1 - sa)))))
out.append('')
# linear filtering of two neighbouring texels, sampled halfway: filtering happens on shader values
a, b = 400, 1000
out.append('static const uint32_t filterCodeA = %d, filterCodeB = %d;' % (a, b))
out.append('static const uint32_t filterLinearBits = 0x%08x;' % bits(f32((decode(a, False) + decode(b, False)) / 2)))
out.append('static const uint32_t filterSrgbBits = 0x%08x;' % bits(f32((decode(a, True) + decode(b, True)) / 2)))
open('fixtures.hpp', 'w').write('\n'.join(out) + '\n')

g = []
g.append('// Generated by gen-fixtures.py. Do not edit.')
g.append('const int valueCount = %d;' % len(values))
g.append('const float fillValues[%d] = float[%d](' % (len(values), len(values)))
g.append(',\n'.join('\tuintBitsToFloat(0x%08xu)' % (bits(f32(v)) if not math.isnan(v) else 0x7fc00000) for v in values))
g.append(');')
open('fill-values.glsl', 'w').write('\n'.join(g) + '\n')
print(len(values), 'values')

# a clear color outside the range of the formats: (1.5, -1.0, 0.5, 2.0)
clear = [1.5, -1.0, 0.5, 2.0]
with open('fixtures.hpp', 'a') as f:
    f.write('\n// clearing to (1.5, -1.0, 0.5, 2.0): red, green, blue and alpha codes\n')
    f.write('static const uint16_t clearLinearCodes[4] = { %s };\n' % ', '.join([str(encode(c, False)) for c in clear[:3]] + [str(encode_alpha(clear[3]))]))
    f.write('static const uint16_t clearSrgbCodes[4] = { %s };\n' % ', '.join([str(encode(c, True)) for c in clear[:3]] + [str(encode_alpha(clear[3]))]))
